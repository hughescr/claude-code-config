#!/usr/bin/env bun
// Generates my-plugins/git-guard/hooks/wordchars.ts: the exact set of characters BSD grep
// (/usr/bin/grep, macOS libc, LANG=en_US.UTF-8) treats as word characters for `\b`.
//
// Method: feed 'restore' + <one code point> through `grep -En 'restore\b'` and record which lines do
// NOT match (no word boundary after "restore" => the code point is a word character).
// Every code point except NUL, \n and surrogates is probed (surrogates cannot be encoded as UTF-8).
//
// Rerun only after a macOS upgrade, while hooks/git-guard.sh still exists as the reference:
//   bun my-plugins/git-guard/tests/gen-git-guard-wordchars.ts   (from ~/.claude)
import { join } from 'node:path'

const GREP = '/usr/bin/grep'
// This file lives in my-plugins/git-guard/tests/, so the target is the sibling hooks/ folder.
const OUT = join(import.meta.dir, '..', 'hooks', 'wordchars.ts')

const run = async (cmd: string[]): Promise<string> => {
  const p = Bun.spawn(cmd, { stdout: 'pipe', stderr: 'pipe' })
  const out = await new Response(p.stdout).text()
  const err = await new Response(p.stderr).text()
  await p.exited
  return (out || err).trim().split('\n')[0] ?? ''
}

const cps: number[] = []
for (let cp = 0; cp < 0x110000; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  if (cp === 0x0a || cp === 0) continue
  cps.push(cp)
}

const input = cps.map(cp => 'restore' + String.fromCodePoint(cp)).join('\n') + '\n'
const p = Bun.spawn([GREP, '-En', 'restore\\b'], {
  stdin: new TextEncoder().encode(input),
  stdout: 'pipe',
  env: { LANG: 'en_US.UTF-8', PATH: '/usr/bin:/bin' },
})
const out = await new Response(p.stdout).text()
await p.exited

// Lines that matched `restore\b` are boundaries; the rest are word characters.
const boundary = new Set(
  out
    .split('\n')
    .filter(Boolean)
    .map(l => Number(l.split(':')[0]) - 1),
)
const word: number[] = []
cps.forEach((cp, i) => {
  if (!boundary.has(i)) word.push(cp)
})

const ranges: [number, number][] = []
for (const cp of word) {
  const last = ranges[ranges.length - 1]
  if (last && last[1] === cp - 1) last[1] = cp
  else ranges.push([cp, cp])
}

// Sanity: the table must be a strict subset of [\p{L}\p{Nd}_] (the header claims it).
const re = /[\p{L}\p{Nd}_]/u
const wordSet = new Set(word)
const notSubset = word.filter(cp => !re.test(String.fromCodePoint(cp)))
const jsOnly = cps.filter(cp => re.test(String.fromCodePoint(cp)) && !wordSet.has(cp)).length
if (notSubset.length > 0) {
  console.error('word chars outside [\\p{L}\\p{Nd}_]:', notSubset.slice(0, 20).map(c => c.toString(16)))
  process.exit(1)
}
if (jsOnly === 0) {
  console.error('table is not a strict subset: no [\\p{L}\\p{Nd}_] code point is a grep boundary; probe is suspect')
  process.exit(1)
}

const hex = (n: number): string => `\\\\u{${n.toString(16)}}`
const cls = ranges.map(([a, b]) => (a === b ? hex(a) : `${hex(a)}-${hex(b)}`)).join('')

const swVers = await run(['/usr/bin/sw_vers', '-productVersion'])
const grepVer = await run([GREP, '--version'])

const file = `// GENERATED by my-plugins/git-guard/tests/gen-git-guard-wordchars.ts: do not edit by hand.
// Generator command : bun my-plugins/git-guard/tests/gen-git-guard-wordchars.ts
// macOS             : ${swVers} (sw_vers -productVersion)
// grep              : ${grepVer} (/usr/bin/grep --version)
// Locale            : LANG=en_US.UTF-8
// Content           : the regex character-class body for exactly the characters BSD grep treats as
//                     word characters for \`\\b\` on this machine: ${ranges.length} ranges, ${word.length} code points.
//                     It is a strict subset of [\\p{L}\\p{Nd}_] (${jsOnly} code points of that class are grep boundaries,
//                     e.g. numerals such as \\u00b2 and \\u2163, and letters newer than macOS libc's Unicode tables).
// Use               : new RegExp(\`[\${WORD_CLASS}]\`, 'u')
export const WORD_CLASS =
  '${cls}'
`
await Bun.write(OUT, file)
console.log(`wrote ${OUT}: ${ranges.length} ranges, ${word.length} code points, ${jsOnly} L|Nd|_ boundaries, ${file.length} bytes`)
