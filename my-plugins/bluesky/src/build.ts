import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const output = fileURLToPath(new URL('../scripts/bsky.mjs', import.meta.url));
const nodeModules = new URL('../node_modules/', import.meta.url);
// Carry runtime dependency licenses in the single distributed file, not a sidecar.
const packages = new Set<string>();
async function collect(name: string): Promise<void> {
  if (packages.has(name)) return;
  packages.add(name);
  const manifest = JSON.parse(await readFile(new URL(`${name}/package.json`, nodeModules), 'utf8')) as { dependencies?: Record<string, string> };
  await Promise.all(Object.keys(manifest.dependencies ?? {}).map(collect));
}
await collect('@atproto/api');
const notices = await Promise.all([...packages].sort().map(async name => {
  const dir = new URL(`${name}/`, nodeModules);
  const entries = await readdir(dir);
  const license = entries.find(file => /^license(?:\.(?:txt|md))?$/i.test(file));
  if (!license) throw new Error(`Missing runtime license for ${name}.`);
  const texts = [await readFile(new URL(license, dir), 'utf8')];
  if (entries.includes('licenses')) {
    const extraDir = new URL('licenses/', dir);
    const extra = (await readdir(extraDir)).sort();
    texts.push(...await Promise.all(extra.map(file => readFile(new URL(file, extraDir), 'utf8'))));
  }
  return `Third-party notices: ${name}\n${texts.join('\n')}`;
}));
const banner = ['Generated by bun run build; edit src/, not this self-contained Node bundle.', ...notices]
  .join('\n').replaceAll(String.fromCodePoint(8232), '\n').replaceAll(String.fromCodePoint(8233), '\n')
  .split(/\r?\n/).map(line => line.trimEnd() ? `// ${line.trimEnd()}` : '//').join('\n');
const result = await Bun.build({
  entrypoints: [fileURLToPath(new URL('./entry.ts', import.meta.url))],
  target: 'node', format: 'esm', minify: true, sourcemap: 'none',
  banner,
});
if (!result.success || result.outputs.length !== 1) throw new Error(`Bundle failed: ${result.logs.join('\n')}`);
const fresh = await result.outputs[0]!.text();
if (process.argv.includes('--check')) {
  const committed = await readFile(output, 'utf8');
  if (committed !== fresh) throw new Error('Committed bundle is stale. Run bun run build.');
  console.log('Bundle matches a fresh build.');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, fresh);
  console.log('Built scripts/bsky.mjs.');
}
